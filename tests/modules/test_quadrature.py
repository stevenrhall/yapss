def test_the_working_precision_is_not_left_set():
    """The rules are computed at 30 digits, and mpmath's global precision, the user's, is left
    as it was, in the process and after importing YAPSS in a fresh one."""
    before = mpmath.mp.dps
    lg(23)  # a size no other test computes, so the rule is not already memoized
    assert mpmath.mp.dps == before
    code = "import mpmath; d = mpmath.mp.dps; import yapss; assert mpmath.mp.dps == d, d"
    subprocess.run([sys.executable, "-c", code], check=True)


@pytest.mark.parametrize(("method", "n"), [("lgl", 5), ("lg", 5), ("lg", 12)])
def test_the_rules_are_exact(method: str, n: int) -> None:
    """Each array of `lgl` and `lg` comes out bit for bit as stored (`lgl` at 10 points is
    `test_lgl`'s).

    A change to how a rule is computed, such as the order of a product in the recurrence, can
    move a node or a weight by an ulp and so every solve by a little; this test says so.
    """
    rule = {"lgl": lgl, "lg": lg}[method]
    for got, stored in zip(rule(n), EXACT[method, n], strict=True):
        np.testing.assert_array_equal(got, np.array(stored))


